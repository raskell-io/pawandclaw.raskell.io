"""Build the website's wiki data and art from the game repository.

    scripts/sync-game.py [GAME_REPO]        # default: ../paw-and-claw

The game is the source of truth. This reads its RON data files (units, terrain,
commanders, factions, damage and movement tables) and its built-in maps (exported
by the game itself: `PAW_EXPORT_MAPS=DIR cargo run`), and writes:

- data/*.json for Zola's load_data, with everything the wiki pages show worked
  out ahead (who builds what, damage either way, which commanders boost a unit)
- content/{units,commanders,maps}/<id>.md, one generated stub page per entry
- static/sprites: portraits, figures, unit sprites, terrain icons, map previews
- the raskell.io stamp and the game's fonts

Re-run it after the game's data or art changes, then commit the result. Pages
under content/ that it writes start with a "generated" note; don't edit those.
"""
