CLASS_NAMES = {
    "Foot": "Foot", "Mech": "Heavy foot", "Wheels": "Wheels", "Treads": "Treads", "Air": "Air",
    "Naval": "Naval", "Transport": "Ground transport", "AirTransport": "Air transport",
    "NavalTransport": "Naval transport",
}
DOMAIN = {"Air": "air", "AirTransport": "air", "Naval": "sea", "NavalTransport": "sea"}


def aw_names():
    """The Advance Wars unit each unit copies, from units.ron's header table."""
    text = (DATA / "units.ron").read_text()
    return {m.group(1): m.group(2).strip() for m in re.finditer(r"^//\s+(\w+)\s+.+?->\s*(.+)$", text, re.M)}


def build(raw):
    factions_raw = raw["factions"]["factions"]
    units_raw = raw["units"]["units"]
    terrain_raw = raw["terrain"]["terrain"]
    cos_raw = raw["commanders"]["commanders"]
    damage_raw = raw["damage"]
    moves_raw = raw["moves"]["costs"]
    aw = aw_names()

    # --- factions
    factions = []
    for key in FACTION_ORDER:
        f = factions_raw[key]
        color = "#" + "".join(f"{round(c * 255):02x}" for c in f["color"][:3])
        factions.append({"id": key, "name": f["name"], "description": f.get("description", ""),
                         "color": color, "animals": f.get("animals", [])})
    faction_by_id = {f["id"]: f for f in factions}

    # --- units (first pass: stats)
    units = []
    for key, u in units_raw.items():
        s = u["stats"]
        lo, hi = s["attack_range"]
        cls = s["class"]
        units.append({
            "id": key, "name": u["name"], "asset": u.get("asset_name", key), "description": u["description"],
            "aw": aw.get(key, ""), "class": cls, "class_name": CLASS_NAMES.get(cls, cls),
            "move_type": snake(cls), "domain": DOMAIN.get(cls, "land"),
            "cost": s["cost"], "movement": s["movement"], "vision": s["vision"],
            "range": [lo, hi], "range_text": "—" if s["attack"] == 0 else (f"{lo}" if lo == hi else f"{lo}–{hi}"),
            "direct": s["attack"] > 0 and hi == 1, "indirect": lo > 1, "attacks": s["attack"] > 0,
            "ammo": s["max_ammo"], "stamina": s["max_stamina"], "daily_stamina": s.get("daily_stamina", 0),
            "can_capture": s["can_capture"], "carries": [CLASS_NAMES[c] for c in s.get("carries", [])],
            "carries_classes": s.get("carries", []), "capacity": s.get("capacity", 0),
        })
    unit_by_id = {u["id"]: u for u in units}

    def matches(filt, unit):
        name, payload = variant(filt)
        foot = unit["class"] in ("Foot", "Mech")
        air = unit["domain"] == "air"
        naval = unit["domain"] == "sea"
        return {
            "All": True, "Direct": unit["direct"], "DirectNonFoot": unit["direct"] and not foot,
            "Indirect": unit["indirect"], "Foot": foot, "NonFoot": not foot,
            "Vehicles": not foot and not air and not naval, "Ground": not air and not naval,
            "Air": air, "Naval": naval, "Transports": unit["capacity"] > 0,
            "Units": payload is not None and unit["id"] in [snake(p) for p in payload],
        }[name]

    # --- terrain
    terrain = []
    for key, t in terrain_raw.items():
        r, g, b = t["color"][:3]
        terrain.append({
            "id": key, "name": t["name"], "description": _sentence(t["description"]), "defense": t["defense"],
            "capturable": t["capturable"], "capture_points": t["capture_points"], "income": t["income"],
            "color": f"#{round(r * 255):02x}{round(g * 255):02x}{round(b * 255):02x}",
            "builds": [CLASS_NAMES[c] for c in t.get("builds", [])], "builds_classes": t.get("builds", []),
            "resupplies": [CLASS_NAMES[c] for c in t.get("resupplies", [])],
            "resupplies_classes": t.get("resupplies", []),
            "hides": key in ("thicket", "lily_pads"),
            "moves": [{"type": c, "name": CLASS_NAMES.get(_camel(c), c), "cost": v}
                      for c, v in moves_raw.get(key, {}).items()],
        })
    terrain_by_id = {t["id"]: t for t in terrain}

    # --- units (second pass: everything that refers to other data)
    primary, secondary = damage_raw["tables"], damage_raw.get("secondary", {})
    for u in units:
        uid = u["id"]
        u["primary"] = [{"id": t, "name": unit_by_id[t]["name"], "asset": unit_by_id[t]["asset"], "damage": d}
                        for t, d in sorted(primary.get(uid, {}).items(), key=lambda kv: -kv[1])]
        u["secondary"] = [{"id": t, "name": unit_by_id[t]["name"], "asset": unit_by_id[t]["asset"], "damage": d}
                          for t, d in sorted(secondary.get(uid, {}).items(), key=lambda kv: -kv[1])]
        taken = []
        for attacker in units:
            p = primary.get(attacker["id"], {}).get(uid)
            q = secondary.get(attacker["id"], {}).get(uid)
            if p is not None or q is not None:
                taken.append({"id": attacker["id"], "name": attacker["name"], "asset": attacker["asset"],
                              "damage": max(x for x in (p, q) if x is not None)})
        u["taken"] = sorted(taken, key=lambda e: -e["damage"])
        u["built_at"] = [t["id"] for t in terrain if u["class"] in t["builds_classes"]]
        u["resupplied_at"] = [t["id"] for t in terrain if u["class"] in t["resupplies_classes"]]
        u["moves"] = [{"id": t["id"], "name": t["name"],
                       "cost": next((m["cost"] for m in t["moves"] if m["type"] == u["move_type"]), 99)}
                      for t in terrain]
        u["carried_by"] = [o["id"] for o in units if u["class"] in o["carries_classes"]]

    # --- commanders
    def unit_list(filt):
        return [u["id"] for u in units if matches(filt, u)]

    def layer_lines(mods):
        lines, boosts = [], []
        for field, label, unit_suffix in [("attack", "attack", "%"), ("defense", "defense", "%"),
                                          ("movement", "movement", ""), ("range", "range", ""),
                                          ("vision", "vision", "")]:
            for filt, amount in mods.get(field, []):
                lines.append(f"{_signed(amount)}{unit_suffix} {label} for {filter_name(filt, unit_by_id)}")
                boosts.append((filt, field, amount))
        for group, amount in mods.get("attack_on", []):
            lines.append(f"{_signed(amount)}% attack for units on {TERRAIN_GROUPS[group]}")
        simple = {
            "attack_per_terrain_star": lambda v: f"{_signed(v)}% attack per terrain star under the attacker",
            "terrain_stars": lambda v: "Terrain defense stars doubled" if v == 100 else f"Terrain defense stars {_signed(v)}%",
            "capture": lambda v: "Captures in a single turn" if v >= 1000 else f"{_signed(v)}% capture speed",
            "cost": lambda v: f"Units cost {_signed(v)}%",
            "luck": lambda v: f"Good luck: up to {_signed(v)}% extra damage (on top of the usual 0–9)",
            "bad_luck": lambda v: f"Bad luck: up to {v}% less damage",
            "counter": lambda v: f"{_signed(v)}% counterattack damage",
            "income": lambda v: f"{_signed(v)} funds per property each day",
            "funds_from_damage": lambda v: f"Earns {v}% of the value of damage dealt as funds",
            "defense_vs_indirect": lambda v: f"{_signed(v)}% defense against indirect fire",
            "repair": lambda v: f"{_signed(v)} HP repaired on properties",
        }
        for field, text in simple.items():
            if mods.get(field):
                lines.append(text(mods[field]))
        for filt, amount in mods.get("daily_stamina", []):
            change = "more" if amount > 0 else "less"
            lines.append(f"{filter_name(filt, unit_by_id).capitalize()} burn {abs(amount)} {change} stamina a day")
        if mods.get("weather_proof"):
            kinds = ", ".join(WEATHER_NAMES.get(w, w) for w in mods["weather_proof"])
            lines.append(f"Not slowed or blinded by {kinds.lower()}")
        flags = {
            "flat_terrain_cost": "Every passable terrain costs 1 movement",
            "hidden_hp": "The enemy can't see your units' HP",
            "see_hidden": "Sees units hidden in thickets and lily pads",
            "counter_first": "When attacked, your units strike back first",
            "build_on_cities": "Storehouses build ground units like workshops",
        }
        for field, text in flags.items():
            if mods.get(field):
                lines.append(text)
        return lines, boosts

    def effect_line(effect):
        name, p = variant(effect)
        if name == "Heal":
            return f"All your units recover {p} HP"
        if name == "DamageEnemies":
            return f"Every enemy unit loses {p} HP"
        if name == "DamageEnemiesOnProperties":
            return f"Enemy units on properties lose {p} HP"
        if name == "HalveEnemyStamina":
            return "Enemy units lose half their stamina"
        if name == "Weather":
            return f"The weather turns to {WEATHER_NAMES.get(p, p).lower()} until your next turn"
        if name == "MultiplyFunds":
            return f"Your funds are multiplied by {p:g}"
        if name == "DrainEnemyPower":
            return f"Drains {p}% of the enemy's power meter for every 5,000 funds you hold"
        if name == "AttackPerFunds":
            return f"{p:g}% more attack for every 1,000 funds you hold"
        if name == "AttackPerProperty":
            return f"{p}% more attack for every property you own"
        if name == "Resupply":
            return "Every unit is resupplied"
        if name == "ExtraMove":
            return f"{filter_name(p, unit_by_id).capitalize()} can move and act again"
        if name == "Reinforce":
            unit = unit_by_id[snake(p["unit"])]["name"]
            return f"A {unit} with {p['hp'] // 10} HP appears on every empty storehouse you own"
        if name == "Meteor":
            hits = "A strike" if p["strikes"] == 1 else f"{p['strikes']} strikes"
            stun = ", and they can't move next turn" if p.get("paralyze") else ""
            return f"{hits} on the densest enemy group: {p['damage']} HP to every enemy within {p['radius']} tiles{stun}"
        return name

    def power_info(pw, kind):
        if not pw:
            return None
        lines, boosts = layer_lines(pw.get("modifiers", {}) or {})
        lines += [effect_line(e) for e in pw.get("effects", []) or []]
        return {"kind": kind, "name": pw["name"], "description": pw["description"], "stars": pw["stars"],
                "lines": lines, "boosts": boosts}

    commanders = []
    for key, c in cos_raw.items():
        faction = snake(c["faction"])
        abilities, ability_boosts = layer_lines(c.get("abilities", {}) or {})
        powers = [p for p in (power_info(c.get("power"), "CO Power"), power_info(c.get("super_power"), "Super CO Power")) if p]
        commanders.append({
            "id": key, "name": c["name"], "faction": faction, "faction_name": faction_by_id[faction]["name"],
            "color": faction_by_id[faction]["color"], "personality": c.get("personality", ""),
            "description": c["description"], "based_on": c.get("based_on", ""),
            "figure": (SPRITES / "figures" / f"{key}.png").is_file(),
            "abilities": abilities, "powers": powers,
            # The old flat fields the home page and cards use
            "power": next(({"name": p["name"], "description": p["description"], "stars": p["stars"]}
                           for p in powers if p["kind"] == "CO Power"), None),
            "super_power": next(({"name": p["name"], "description": p["description"], "stars": p["stars"]}
                                 for p in powers if p["kind"] == "Super CO Power"), None),
            "_boosts": [("Always", *b) for b in ability_boosts] + [(p["kind"], *b) for p in powers for b in p["boosts"]],
        })
        for p in powers:
            del p["boosts"]

    # Which commanders change each unit, always or during a power
    for u in units:
        u["commanders"] = []
        for co in commanders:
            notes = [f"{_signed(amount)}{'%' if field in ('attack', 'defense') else ''} {field}"
                     + ("" if when == "Always" else f" ({when})")
                     for when, filt, field, amount in co["_boosts"] if matches(filt, u)]
            if notes:
                u["commanders"].append({"id": co["id"], "name": co["name"], "notes": notes})
    for co in commanders:
        del co["_boosts"]

    for f in factions:
        f["commanders"] = [c["id"] for c in commanders if c["faction"] == f["id"]]

    damage = {
        "units": [{"id": u["id"], "name": u["name"], "asset": u["asset"]} for u in units],
        "rows": [{"id": a["id"], "name": a["name"], "asset": a["asset"],
                  "cells": [_cell(primary.get(a["id"], {}).get(d["id"]), secondary.get(a["id"], {}).get(d["id"]))
                            for d in units]} for a in units],
    }
    return {"factions": factions, "units": units, "terrain": terrain, "commanders": commanders, "damage": damage}


TERRAIN_GROUPS = {"Plains": "grass (plains)", "Roads": "trails (roads)", "Properties": "properties"}
WEATHER_NAMES = {"Clear": "Clear", "Rain": "Rain", "Snow": "Snow", "Sandstorm": "Sandstorm", "Fog": "Dense fog"}
FILTER_NAMES = {
    "All": "all units", "Direct": "direct-combat units", "DirectNonFoot": "direct-combat units other than foot soldiers",
    "Indirect": "indirect (ranged) units", "Foot": "foot soldiers", "NonFoot": "all units but foot soldiers",
    "Vehicles": "ground vehicles", "Ground": "ground units", "Air": "fliers", "Naval": "boats",
    "Transports": "transports",
}


def filter_name(filt, unit_by_id):
    name, payload = variant(filt)
    if name == "Units":
        names = [unit_by_id[snake(p)]["name"] + "s" for p in payload]
        return names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]
    return FILTER_NAMES[name]


def _signed(v):
    return f"+{v:g}" if v > 0 else f"−{abs(v):g}"


def _camel(snake_name):
    return "".join(part.capitalize() for part in snake_name.split("_"))


def _sentence(text):
    """`Open grassland - minimal cover` -> `Open grassland: minimal cover`."""
    return text.replace(" - ", ": ")


def _cell(p, q):
    if p is None and q is None:
        return None
    return {"p": p, "s": q, "best": max(x for x in (p, q) if x is not None)}

