# ---------------------------------------------------------------------------
# RON
# ---------------------------------------------------------------------------

TOKEN = re.compile(r"""
    (?P<ws>\s+|//[^\n]*|/\*.*?\*/)
  | (?P<str>"(?:[^"\\]|\\.)*")
  | (?P<char>'(?:[^'\\]|\\.)')
  | (?P<num>-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?)
  | (?P<ident>[A-Za-z_][A-Za-z0-9_]*)
  | (?P<punct>[()\[\]{},:])
""", re.S | re.X)


def ron(text):
    """Parse RON into Python values.

    Structs and maps become dicts, lists and tuples lists, `Some(x)` is x and
    `None` None. A bare enum variant is its name; one with a payload is
    {"Variant": payload} (the payload's single value, or a dict of its fields).
    """
    tokens = []
    for m in TOKEN.finditer(text):
        kind = m.lastgroup
        if kind != "ws":
            tokens.append((kind, m.group()))
    pos = 0

    def peek(offset=0):
        return tokens[pos + offset] if pos + offset < len(tokens) else (None, None)

    def take(expected=None):
        nonlocal pos
        tok = tokens[pos]
        if expected and tok[1] != expected:
            raise ValueError(f"expected {expected!r}, got {tok[1]!r}")
        pos += 1
        return tok

    def seq(close):
        """Values up to `close`: a dict if they're `name: value` fields, else a list."""
        if peek()[0] == "ident" and peek(1)[1] == ":":
            out = {}
            while peek()[1] != close:
                name = take()[1]
                take(":")
                out[name] = value()
                if peek()[1] == ",":
                    take(",")
            take(close)
            return out
        out = []
        while peek()[1] != close:
            out.append(value())
            if peek()[1] == ",":
                take(",")
        take(close)
        return out

    def value():
        kind, tok = take()
        if kind == "str":
            return json.loads(tok)
        if kind == "char":
            return tok[1:-1]
        if kind == "num":
            return float(tok) if any(c in tok for c in ".eE") else int(tok)
        if tok == "(":
            return seq(")")
        if tok == "[":
            return seq("]")
        if tok == "{":
            out = {}
            while peek()[1] != "}":
                key = value()
                take(":")
                out[key] = value()
                if peek()[1] == ",":
                    take(",")
            take("}")
            return out
        if kind == "ident":
            if tok in ("true", "false"):
                return tok == "true"
            if tok == "None":
                return None
            if peek()[1] == "(":
                take("(")
                payload = seq(")")
                if tok == "Some":
                    return payload[0] if isinstance(payload, list) else payload
                if isinstance(payload, list) and len(payload) == 1:
                    payload = payload[0]
                return {tok: payload}
            return tok
        raise ValueError(f"unexpected {tok!r}")

    return value()


def load(name):
    return ron((DATA / f"{name}.ron").read_text())


def snake(name):
    """`TallGrass` -> `tall_grass`, the RON keys' spelling of an enum variant."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def variant(v):
    """The name and payload of an enum value: `"All"` or `{"Units": [...]}`."""
    if isinstance(v, dict):
        (name, payload), = v.items()
        return name, payload
    return v, None

