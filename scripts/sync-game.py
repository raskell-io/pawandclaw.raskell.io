def export_maps():
    """The built-in maps, as the game sets them up, via `PAW_EXPORT_MAPS`."""
    with tempfile.TemporaryDirectory() as out:
        env = dict(os.environ, PAW_EXPORT_MAPS=out)
        try:
            subprocess.run(["cargo", "run", "--quiet"], cwd=GAME, env=env, check=True, stdout=subprocess.DEVNULL)
        except (OSError, subprocess.CalledProcessError) as err:
            print(f"warning: couldn't export the game's maps ({err}); keeping data/maps.json")
            return None
        return {p.stem: json.loads(p.read_text()) for p in Path(out).glob("*.json")}


def slug(map_id):
    return snake(map_id).replace("_", "-")


def maps_data(exported, data, order):
    terrain_by_id = {t["id"]: t for t in data["terrain"]}
    faction_by_id = {f["id"]: f for f in data["factions"]}
    out = []
    for map_id in order:
        m = exported[map_id]
        grid = [[snake(t) for t in row] for row in m["terrain"]]
        # Players pick the armies at setup, so show the map's first army in Western
        # colours, its second in Northern and so on, as the skirmish menu does
        seats = {o: FACTION_ORDER[i] for i, o in enumerate(dict.fromkeys(snake(p["owner"]) for p in m["properties"]))}
        owners = {(p["x"], p["y"]): seats[snake(p["owner"])] for p in m["properties"]}
        armies = list(seats.values())
        counts = {}
        for row in grid:
            for t in row:
                counts[t] = counts.get(t, 0) + 1
        properties = []
        for t in data["terrain"]:
            if not t["capturable"] or not counts.get(t["id"]):
                continue
            per = {a: sum(1 for (x, y), o in owners.items() if o == a and grid[y][x] == t["id"]) for a in armies}
            neutral = counts[t["id"]] - sum(per.values())
            properties.append({"id": t["id"], "name": t["name"], "total": counts[t["id"]], "neutral": neutral,
                               "owned": [per[a] for a in armies]})
        income = [sum(terrain_by_id[grid[y][x]]["income"] for (x, y), o in owners.items() if o == a) for a in armies]
        out.append({
            "id": slug(map_id), "key": map_id, "name": m["name"], "description": m.get("description", ""),
            "width": m["width"], "height": m["height"], "war_room": "War Room" in m.get("description", "")
            or map_id in WAR_ROOM, "armies": [{"id": a, "name": ARMY_SEATS[i], "color": faction_by_id[a]["color"]}
                                              for i, a in enumerate(armies)],
            "starting_income": income, "units": len(m["units"]), "properties": properties,
            "property_count": sum(p["total"] for p in properties),
            "terrain": [{"id": t, "name": terrain_by_id[t]["name"], "count": n}
                        for t, n in sorted(counts.items(), key=lambda kv: -kv[1])],
            "_grid": grid, "_owners": owners,
        })
    return out


ARMY_SEATS = ["First army", "Second army", "Third army", "Fourth army", "Fifth army"]

# The maps copied tile for tile from the Advance Wars War Room
WAR_ROOM = {"SpannIsland", "SoleHarbor", "PivotIsle", "RidgeIsland", "TwinIsle", "MojiIsland", "DuoFalls",
            "ToilFerry", "PointStormy"}


def terrain_icons(terrain):
    """32x32 icons: the tile's first frame with its feature on top, plus each army's colours for properties."""
    tiles = SPRITES / "terrain" / "tiles"
    features = SPRITES / "terrain" / "features"
    out = STATIC / "sprites" / "terrain"
    out.mkdir(parents=True, exist_ok=True)
    for t in terrain:
        tid = t["id"]
        layers = [str(tiles / f"{tid}.png") + "[32x32+0+0]"]
        # Trails draw as paths in the game; the log feature isn't shown on them
        if tid != "log" and (features / f"{tid}.png").is_file():
            layers.append(str(features / f"{tid}.png"))
        if tid == "log":
            # Show a trail as the game draws it: a path crossing the tile
            shutil.copy2(trail_icon(Path(tempfile.mkdtemp()), [["log", "log", "log"]], 1, 0), out / "log.png")
            continue
        _compose(layers, out / f"{tid}.png")
        for faction in FACTION_ORDER:
            colored = features / faction / f"{tid}.png"
            if colored.is_file():
                (out / faction).mkdir(exist_ok=True)
                _compose([layers[0], str(colored)], out / faction / f"{tid}.png")


def _compose(layers, dst):
    cmd = ["magick", layers[0], "+repage"]
    for layer in layers[1:]:
        cmd += [layer, "-composite"]
    subprocess.run(cmd + ["-strip", str(dst)], check=True)


# Trails join each other and the buildings they lead to
TRAIL_LINKS = {"log", "base", "workshop", "dock", "roost", "outpost", "storehouse", "hollow"}


def trail_icon(cache, grid, x, y):
    """A trail tile as the game draws it: a dirt path reaching toward its neighbours."""
    h, w = len(grid), len(grid[0])
    links = [0 <= y + dy < h and 0 <= x + dx < w and grid[y + dy][x + dx] in TRAIL_LINKS
             for dx, dy in [(0, -1), (1, 0), (0, 1), (-1, 0)]]
    path = cache / ("trail-" + "".join("1" if l else "0" for l in links) + ".png")
    if not path.exists():
        rects = ["rectangle 10,10 21,21"]
        for linked, rect in zip(links, ["10,0 21,10", "21,10 31,21", "10,21 21,31", "0,10 10,21"]):
            if linked:
                rects.append("rectangle " + rect)
        draw = ["-fill", "#a8834f"] + sum((["-draw", r] for r in rects), [])
        inner = [r.replace("rectangle ", "") for r in rects]
        shrunk = []
        for r in inner:
            (x0, y0), (x1, y1) = [tuple(int(v) for v in c.split(",")) for c in r.split()]
            shrunk.append(f"rectangle {x0 + (1 if x0 > 0 else 0)},{y0 + (1 if y0 > 0 else 0)} "
                          f"{x1 - (1 if x1 < 31 else 0)},{y1 - (1 if y1 < 31 else 0)}")
        draw += ["-fill", "#caa46c"] + sum((["-draw", r] for r in shrunk), [])
        tile = SPRITES / "terrain" / "tiles" / "grass.png"
        subprocess.run(["magick", str(tile) + "[32x32+0+0]", "+repage", *draw, str(path)], check=True)
    return path


def map_previews(maps):
    """Each map drawn from the terrain icons, one 32x32 tile per cell (scaled down in CSS)."""
    icons = STATIC / "sprites" / "terrain"
    out = STATIC / "img" / "maps"
    out.mkdir(parents=True, exist_ok=True)
    trails = Path(tempfile.mkdtemp())
    for m in maps:
        grid = m["_grid"]
        rows = []
        for y, row in enumerate(grid):
            cells = []
            for x, t in enumerate(row):
                owner = m["_owners"].get((x, y))
                icon = icons / owner / f"{t}.png" if owner and (icons / owner / f"{t}.png").is_file() else icons / f"{t}.png"
                if t == "log":
                    icon = trail_icon(trails, grid, x, y)
                cells.append(str(icon))
            rows += ["(", *cells, "+append", ")"]
        subprocess.run(["magick", *rows, "-append", "-define", "webp:lossless=true", str(out / f"{m['id']}.webp")],
                       check=True)

