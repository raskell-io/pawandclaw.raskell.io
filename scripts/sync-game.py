def stub(path, title, template, description, extra, weight=0):
    lines = ["+++", GENERATED.rstrip(), f"title = {json.dumps(title)}", f"description = {json.dumps(description)}",
             f'template = "{template}"']
    if weight:
        lines.append(f"weight = {weight}")
    lines.append("[extra]")
    lines += [f"{k} = {json.dumps(v)}" for k, v in extra.items()]
    lines.append("+++")
    path.write_text("\n".join(lines) + "\n")


def write_stubs(folder, items, make):
    """Rewrite content/<folder>/<id>.md for each item; stale generated pages go."""
    root = SITE / "content" / folder
    root.mkdir(parents=True, exist_ok=True)
    keep = set()
    for i, item in enumerate(items, 1):
        path = root / f"{item['id']}.md"
        title, template, description, extra = make(item)
        stub(path, title, template, description, extra, weight=i)
        keep.add(path.name)
    for path in root.glob("*.md"):
        if path.name != "_index.md" and path.name not in keep and GENERATED.strip() in path.read_text():
            path.unlink()


def copy_tree(src, dst, pattern="*.png"):
    dst.mkdir(parents=True, exist_ok=True)
    for path in sorted(src.glob(pattern)):
        shutil.copy2(path, dst / path.name)


def fonts():
    """The game's Alegreya fonts, as woff2 when fontTools is around (only when they changed)."""
    dst = STATIC / "fonts"
    dst.mkdir(parents=True, exist_ok=True)
    for ttf in sorted((GAME / "assets" / "fonts").glob("*")):
        if ttf.suffix != ".ttf":
            shutil.copy2(ttf, dst / ttf.name)
            continue
        target = dst / (ttf.stem + ".woff2")
        if target.exists() and target.stat().st_mtime >= ttf.stat().st_mtime:
            continue
        try:
            from fontTools.ttLib import TTFont
            font = TTFont(ttf)
            font.flavor = "woff2"
            font.save(target)
        except ImportError:
            shutil.copy2(ttf, dst / ttf.name)


def write_json(name, value):
    (SITE / "data" / f"{name}.json").write_text(json.dumps({name: value}, indent=2, ensure_ascii=False) + "\n")
    print(f"data/{name}.json: {len(value)}")


def main():
    if not DATA.is_dir():
        sys.exit(f"no game data at {DATA}; pass the paw-and-claw checkout as the first argument")
    (SITE / "data").mkdir(exist_ok=True)
    raw = {name: load(file) for name, file in [("factions", "factions"), ("units", "units"), ("terrain", "terrain"),
                                                ("commanders", "commanders"), ("damage", "damage_tables"),
                                                ("moves", "movement_costs")]}
    data = build(raw)
    for name in ("factions", "units", "terrain", "commanders", "damage"):
        write_json(name, data[name])

    terrain_icons(data["terrain"])
    exported = export_maps()
    if exported:
        order = [m for m in MAP_ORDER if m in exported] + sorted(set(exported) - set(MAP_ORDER))
        maps = maps_data(exported, data, order)
        map_previews(maps)
        write_json("maps", [{k: v for k, v in m.items() if not k.startswith("_")} for m in maps])
        write_stubs("maps", maps, lambda m: (m["name"], "map.html", m["description"] or f"{m['name']}, a {m['width']}×{m['height']} battlefield.", {"id": m["id"]}))

    write_stubs("units", data["units"], lambda u: (
        u["name"], "unit.html", f"{u['name']}: {u['description']}. Stats, damage chart and matchups.", {"id": u["id"]}))
    write_stubs("commanders", data["commanders"], lambda c: (
        c["name"], "commander.html", f"{c['name']} of the {c['faction_name']}: {c['description']}", {"id": c["id"]}))

    copy_tree(SPRITES / "portraits", STATIC / "sprites" / "portraits")
    copy_tree(SPRITES / "figures", STATIC / "sprites" / "figures")
    # The raskell.io seal stamped in the game's opening
    shutil.copy2(SPRITES / "brand" / "stamp_ink.png", STATIC / "img" / "raskell-stamp.png")
    for faction in FACTION_ORDER:
        copy_tree(SPRITES / "units" / faction, STATIC / "sprites" / "units" / faction)
    fonts()
    print("sprites, terrain icons, map previews and fonts done")


